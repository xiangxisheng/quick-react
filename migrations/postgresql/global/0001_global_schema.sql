CREATE TABLE IF NOT EXISTS global_sites (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	site_key VARCHAR(64) NOT NULL UNIQUE CHECK (site_key ~ '^[a-z][a-z0-9_]*$'),
	name VARCHAR(255) NOT NULL,
	base_site_key VARCHAR(64),
	dsn TEXT NOT NULL DEFAULT '',
	dsn_password TEXT,
	database_binding VARCHAR(64) NOT NULL DEFAULT '',
	status VARCHAR(32) NOT NULL DEFAULT 'enabled',
	migration_status VARCHAR(32) NOT NULL DEFAULT 'ready',
	is_default SMALLINT NOT NULL DEFAULT 0 CHECK (is_default IN (0, 1)),
	is_system SMALLINT NOT NULL DEFAULT 0 CHECK (is_system IN (0, 1)),
	passport_sso_enabled SMALLINT NOT NULL DEFAULT 0 CHECK (passport_sso_enabled IN (0, 1))
);
CREATE UNIQUE INDEX IF NOT EXISTS global_sites_one_default ON global_sites(is_default) WHERE is_default = 1 AND status = 'enabled';

CREATE TABLE IF NOT EXISTS global_site_hosts (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	hostname VARCHAR(255) NOT NULL UNIQUE,
	site_key VARCHAR(64) NOT NULL REFERENCES global_sites(site_key),
	status VARCHAR(32) NOT NULL DEFAULT 'enabled',
	created_at BIGINT NOT NULL
);


CREATE TABLE IF NOT EXISTS passport_telegram_updates (
	bot_id BIGINT NOT NULL,
	update_id BIGINT NOT NULL,
	status VARCHAR(32) NOT NULL CHECK (status IN ('processing', 'completed', 'failed')),
	created_at BIGINT NOT NULL,

CREATE TABLE IF NOT EXISTS passport_users (
	user_id BIGINT PRIMARY KEY CHECK (user_id >= 4194304),
	nickname VARCHAR(48) NOT NULL CHECK (LENGTH(TRIM(nickname)) BETWEEN 1 AND 12),
	status VARCHAR(32) NOT NULL DEFAULT 'enabled' CHECK (status IN ('enabled', 'disabled')),
	created_at BIGINT NOT NULL,
	updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS passport_user_credentials (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES passport_users(user_id) ON DELETE RESTRICT,
	password TEXT NOT NULL CHECK (LENGTH(TRIM(password)) > 0),
	created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS passport_user_credentials_user_created ON passport_user_credentials(user_id, created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS passport_sessions (
	id VARCHAR(128) PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES passport_users(user_id) ON DELETE RESTRICT,
	expires_at BIGINT NOT NULL,
	created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS passport_sessions_user_id ON passport_sessions(user_id);
CREATE INDEX IF NOT EXISTS passport_sessions_expires_at ON passport_sessions(expires_at);

CREATE TABLE IF NOT EXISTS passport_telegram_accounts (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES passport_users(user_id) ON DELETE RESTRICT,
	bot_id BIGINT NOT NULL,
	telegram_user_id BIGINT NOT NULL,
	chat_id BIGINT NOT NULL,
	nickname VARCHAR(48) NOT NULL CHECK (LENGTH(TRIM(nickname)) BETWEEN 1 AND 12),
	created_at BIGINT NOT NULL,
	updated_at BIGINT NOT NULL,
	UNIQUE (user_id, bot_id, telegram_user_id),
	UNIQUE (bot_id, telegram_user_id)
);

CREATE TABLE IF NOT EXISTS passport_oauth_accounts (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES passport_users(user_id) ON DELETE RESTRICT,
	provider VARCHAR(64) NOT NULL,
	provider_user_id VARCHAR(512) NOT NULL,
	created_at BIGINT NOT NULL,
	updated_at BIGINT NOT NULL,
	UNIQUE (user_id, provider, provider_user_id),
	UNIQUE (provider, provider_user_id)
);

CREATE TABLE IF NOT EXISTS passport_emails (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	email VARCHAR(320) NOT NULL UNIQUE,
	verified SMALLINT NOT NULL DEFAULT 0 CHECK (verified IN (0, 1)),
	created_at BIGINT NOT NULL,
	updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS passport_user_emails (
	user_id BIGINT NOT NULL REFERENCES passport_users(user_id) ON DELETE RESTRICT,
	email_id BIGINT NOT NULL UNIQUE REFERENCES passport_emails(id) ON DELETE RESTRICT,
	is_primary SMALLINT NOT NULL DEFAULT 0 CHECK (is_primary IN (0, 1)),
	created_at BIGINT NOT NULL,
	PRIMARY KEY (user_id, email_id)
);

CREATE TABLE IF NOT EXISTS passport_email_otp (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	bot_id BIGINT NOT NULL,
	telegram_user_id BIGINT NOT NULL,
	chat_id BIGINT NOT NULL,
	email VARCHAR(320) NOT NULL,
	code_hash TEXT NOT NULL,
	attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
	status VARCHAR(32) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'used', 'expired')),
	expires_at BIGINT NOT NULL,
	created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS passport_email_otp_lookup ON passport_email_otp(bot_id, telegram_user_id, status, created_at DESC);

CREATE TABLE IF NOT EXISTS passport_user_roles (
	user_id BIGINT NOT NULL REFERENCES passport_users(user_id) ON DELETE RESTRICT,
	role VARCHAR(128) NOT NULL,
	created_at BIGINT NOT NULL,
	PRIMARY KEY (user_id, role)
);

CREATE TABLE IF NOT EXISTS passport_group_prompts (

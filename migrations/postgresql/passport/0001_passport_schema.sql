);
CREATE INDEX IF NOT EXISTS passport_telegram_updates_status ON passport_telegram_updates(status, updated_at);

CREATE TABLE IF NOT EXISTS passport_telegram_identity_choices (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	bot_id BIGINT NOT NULL,
	telegram_user_id BIGINT NOT NULL,
	chat_id BIGINT NOT NULL,
	target_user_id BIGINT NOT NULL REFERENCES passport_users(user_id) ON DELETE RESTRICT,
	email VARCHAR(320) NOT NULL,
	status VARCHAR(32) NOT NULL CHECK (status IN ('pending', 'confirmed', 'cancelled', 'expired')),
	expires_at BIGINT NOT NULL,
	created_at BIGINT NOT NULL,
	updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS passport_telegram_identity_choices_lookup ON passport_telegram_identity_choices(bot_id, telegram_user_id, status, created_at DESC);

CREATE TABLE IF NOT EXISTS passport_login_challenges (
	id VARCHAR(128) PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES passport_users(user_id) ON DELETE RESTRICT,
	bot_id BIGINT NOT NULL,
	telegram_user_id BIGINT NOT NULL,
	chat_id BIGINT NOT NULL,
	expected_number INTEGER NOT NULL CHECK (expected_number BETWEEN 1 AND 99),
	status VARCHAR(32) NOT NULL CHECK (status IN ('pending', 'approved', 'denied', 'expired', 'consumed')),
	expires_at BIGINT NOT NULL,
	created_at BIGINT NOT NULL,
	updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS passport_login_challenges_identity ON passport_login_challenges(bot_id, telegram_user_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS passport_login_challenges_expires ON passport_login_challenges(status, expires_at);

